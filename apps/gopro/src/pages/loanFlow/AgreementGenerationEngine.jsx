import React, { useMemo, useState } from 'react';
import { useNavigate, useSearchParams } from 'react-router-dom';
import { EventPublisher } from '../../workflow/EventPublisher';
import { buildPageMetadata } from '../../workflow/pageMetadata';
import { publicErrorMessage } from '../../utils/security';
import BackendStepPage from '../../components/ui/BackendStepPage';

export default function AgreementGenerationEngine({ metadata }) {
  const navigate = useNavigate();
  const [searchParams] = useSearchParams();
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState('');

  const workflowMetadata = useMemo(() => buildPageMetadata({
    defaultStateId: 'LENDER-AGREEMENT-V1-AGREEMENT-GENERATION-V1',
    metadata,
    searchParams,
    routePath: '/loan-flow/agreement-generation',
  }), [metadata, searchParams]);

  const handleNext = async () => {
    setError('');
    setSubmitting(true);
    try {
      await EventPublisher.publishAndNavigate({
        navigate,
        searchParams,
        eventType: 'AGREEMENT_GENERATION_SUBMITTED',
        formData: {},
        workflowMetadata,
      });
    } catch (err) {
      setError(publicErrorMessage(err, 'Agreement generation failed. Please try again.'));
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <BackendStepPage
      eyebrow="Lender · Agreement"
      title="Loan agreement generation"
      description="The loan agreement is generated by the lender from the accepted offer. No agreement terms are generated in the browser."
      checks={[
        'The lender generates the agreement from the sanctioned offer.',
        'The agreement is made available for the borrower e-sign step.',
        'The loan service resolves the next workflow step.',
      ]}
      processingTitle="Generating the loan agreement"
      processingDescription="The lender is preparing the agreement document."
      processingSteps={[
        'Sending the generation request',
        'Waiting for the agreement document',
        'Resolving the next workflow step',
      ]}
      submitLabel="Generate agreement"
      loadingLabel="Generating…"
      submitting={submitting}
      error={error}
      hint="The agreement is generated only after you submit."
      onBack={() => navigate(-1)}
      onSubmit={handleNext}
    />
  );
}
